def score(test: PsyTest, answers: dict[int, str]) -> dict[str, int]:
    """Answers {question id: "a" | "b"} -> points per category."""
    points = {c.key: 0 for c in test.categories}
    for q in test.questions:
        points[q.a_key if answers[q.id] == "a" else q.b_key] += 1
    return points


def leading(points: dict[str, int]) -> list[str]:
    """The category (or several, if they tie) with the most points."""
    top = max(points.values())
    return [key for key, value in points.items() if value == top]
