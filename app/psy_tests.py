"""Psychological tests: "Пять языков любви" and "Пять языков извинений".

Method (after Gary Chapman's questionnaires): every question is a forced choice
between two statements, each belonging to a different "language". Every pair of
languages is compared the same number of times, so every language can score the
same maximum. Points = how many times that language was chosen. Because the
languages compete with each other, "all 100%" is impossible.

The statements are written for this app (Chapman's original items are part of
his copyrighted books); the method and the five categories follow the source.
"""

from dataclasses import dataclass
from itertools import combinations


@dataclass(frozen=True)
class Category:
    key: str
    title: str
    description: str
    advice: str  # what the partner can do


@dataclass(frozen=True)
class Question:
    id: int
    a_key: str
    a_text: str
    b_key: str
    b_text: str


@dataclass(frozen=True)
class PsyTest:
    id: str
    title: str
    subtitle: str
    prompt: str  # shown above every pair of statements
    advice_title: str
    categories: tuple[Category, ...]
    questions: tuple[Question, ...]

    @property
    def max_points(self) -> int:
        """How many times each category appears — the highest possible score."""
        return 2 * len(self.questions) // len(self.categories)


def _build_questions(statements: dict[str, list[str]], rounds: int) -> tuple[Question, ...]:
    """Pair every two categories `rounds` times, taking each statement once.

    Question order is mixed (rounds are interleaved) and the side (A/B) alternates,
    so neither the position nor the order gives the categories away.
    """
    keys = list(statements)
    pairs = list(combinations(keys, 2))
    next_statement = {k: 0 for k in keys}
    # A fixed mixing order for the 10 pairs, so the same two languages never meet twice in a row.
    order = [0, 7, 3, 9, 5, 1, 8, 4, 6, 2]
    questions = []
    for r in range(rounds):
        for i in order:
            a, b = pairs[i]
            if (r + i) % 2:
                a, b = b, a
            qid = len(questions) + 1
            questions.append(
                Question(
                    id=qid,
                    a_key=a,
                    a_text=statements[a][next_statement[a]],
                    b_key=b,
                    b_text=statements[b][next_statement[b]],
                )
            )
            next_statement[a] += 1
            next_statement[b] += 1
    for k in keys:
        assert next_statement[k] == len(statements[k]), f"{k}: every statement must be used once"
    return tuple(questions)


